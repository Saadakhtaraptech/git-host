<?php
// for loop 

for($a = 1; $a <= 10; $a++){
    echo "2 x " . $a . " = " . (2 * $a) . "<br>";
}

for($a = 10; $a >= 1; $a--){
    echo "2 x " . $a . " = " . (2 * $a) . "<br>";
}


// while loop

$a = 11;
while($a <= 16){
    echo 'This is while loop ' . $a . "<br>";
    $a++;
}

?>